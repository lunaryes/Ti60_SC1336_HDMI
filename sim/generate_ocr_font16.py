"""Generate camera-normalized 16x16 OCR templates and grayscale RTL stimuli.

Requires Pillow. All outputs go below the explicit --output-dir. ROM order is
class * 8 + font * 2 + occupancy, with digits before uppercase Latin letters.
The 16x16 bitmap is tight, without padding; bit 255 is its top-left pixel.

Narrow-stroke convention: floor-based source binning leaves empty output cells
when a source span is less than 16 pixels. The live RTL separately upsamples an
almost-solid narrow vertical stroke to a full 16x16 rectangle, while retaining
its original aspect ratio for matching. Such a glyph can match a solid thick-I
template. This script deliberately retains the original floor-bin ROM data;
changing this convention requires coordinated RTL and template regeneration.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont, ImageOps


CHARACTERS = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"
FONTS = (
    ("arial", "arial.ttf"),
    ("arial_bold", "arialbd.ttf"),
    ("consolas", "consola.ttf"),
    ("consolas_bold", "consolab.ttf"),
)
OCCUPANCY_PERCENT = (25, 40)
GRID = 16


def render_glyph(character: str, font_path: Path, font_size: int) -> Image.Image:
    """Return a tight antialiased black glyph on a white grayscale background."""
    font = ImageFont.truetype(str(font_path), font_size)
    left, top, right, bottom = font.getbbox(character)
    canvas = Image.new("L", (right - left + 16, bottom - top + 16), 255)
    ImageDraw.Draw(canvas).text((8 - left, 8 - top), character, font=font, fill=0)
    binary = canvas.point(lambda value: 255 if value < 128 else 0)
    bbox = binary.getbbox()
    if bbox is None:
        raise ValueError(f"Empty rendered character: {character!r}")
    return canvas.crop(bbox)


def normalized_bitmap(
    grayscale: Image.Image, occupancy_percent: int, dark_foreground: bool = True
) -> tuple[int, tuple[int, int, int, int] | None]:
    """Match the RTL: foreground threshold 128 and floor(pos*16/span) bins."""
    pixels = list(grayscale.convert("L").get_flattened_data())
    width, height = grayscale.size
    foreground = [value < 128 if dark_foreground else value >= 128 for value in pixels]
    points = [(offset % width, offset // width) for offset, value in enumerate(foreground) if value]
    if not points:
        return 0, None
    xmin = min(point[0] for point in points)
    xmax = max(point[0] for point in points)
    ymin = min(point[1] for point in points)
    ymax = max(point[1] for point in points)
    span_x, span_y = xmax - xmin + 1, ymax - ymin + 1
    hits, totals = [0] * 256, [0] * 256
    for y in range(ymin, ymax + 1):
        row = ((y - ymin) * GRID) // span_y
        for x in range(xmin, xmax + 1):
            col = ((x - xmin) * GRID) // span_x
            cell = row * GRID + col
            totals[cell] += 1
            hits[cell] += int(foreground[y * width + x])
    bitmap = 0
    for count, total in zip(hits, totals):
        bitmap = (bitmap << 1) | int(total > 0 and count * 100 >= total * occupancy_percent)
    return bitmap, (xmin, ymin, xmax + 1, ymax + 1)


def aspect_ratio(width: int, height: int) -> int:
    return min(255, round(width * 128 / height))


def template_records(font_dir: Path) -> list[dict]:
    records = []
    for class_index, character in enumerate(CHARACTERS):
        for font_index, (font_name, filename) in enumerate(FONTS):
            glyph = render_glyph(character, font_dir / filename, 128)
            for occupancy_index, occupancy in enumerate(OCCUPANCY_PERCENT):
                bitmap, bbox = normalized_bitmap(glyph, occupancy)
                assert bbox is not None and 0 < bitmap <= (1 << 256) - 1
                records.append({
                    "address": class_index * 8 + font_index * 2 + occupancy_index,
                    "class_id": class_index + 1,
                    "ascii": ord(character),
                    "character": character,
                    "font": font_name,
                    "occupancy_percent": occupancy,
                    "bitmap_hex": f"{bitmap:064X}",
                    "foreground_cells": bitmap.bit_count(),
                    "aspect": aspect_ratio(glyph.width, glyph.height),
                    "source_width": glyph.width,
                    "source_height": glyph.height,
                })
    assert len(records) == 288
    assert [record["address"] for record in records] == list(range(288))
    return records


def write_rom(path: Path, records: list[dict]) -> None:
    lines = [
        "`timescale 1ns / 1ps",
        "// Generated by sim/generate_ocr_font16.py. Do not hand-edit.",
        "// 36 classes x 4 fonts x 2 occupancy thresholds. Tight 16x16 glyphs.",
        "// bitmap_o[255] is row 0, column 0; class IDs are 1..36.",
        "module ocr_font16_rom (",
        "    input wire [8:0] addr_i,",
        "    output reg [255:0] bitmap_o,",
        "    output reg [5:0] class_o,",
        "    output reg [7:0] ascii_o,",
        "    output reg [7:0] aspect_o",
        ");",
        "    always @(*) begin",
        "        bitmap_o = 256'd0; class_o = 6'd0; ascii_o = 8'd0; aspect_o = 8'd0;",
        "        case (addr_i)",
    ]
    for record in records:
        lines.append(
            f"            9'd{record['address']}: begin "
            f"bitmap_o = 256'h{record['bitmap_hex']}; "
            f"class_o = 6'd{record['class_id']}; "
            f"ascii_o = 8'h{record['ascii']:02X}; "
            f"aspect_o = 8'd{record['aspect']}; end "
            f"// {record['character']} {record['font']} {record['occupancy_percent']}%"
        )
    lines.extend(["            default: begin end", "        endcase", "    end", "endmodule", ""])
    path.write_text("\n".join(lines), encoding="ascii")


def make_stimuli(output_dir: Path, font_dir: Path) -> list[dict]:
    stimulus_dir = output_dir / "stimuli"
    stimulus_dir.mkdir(parents=True, exist_ok=True)
    records = []

    def save(name: str, image: Image.Image, expected: str | None, polarity: str, **details) -> None:
        image = image.convert("L")
        hex_path = stimulus_dir / f"{name}.hex"
        hex_path.write_text("".join(f"{value:02X}\n" for value in image.get_flattened_data()), encoding="ascii")
        image.save(stimulus_dir / f"{name}.png")
        dark = polarity != "light_on_dark"
        bitmap, bbox = normalized_bitmap(image, 25, dark)
        records.append({
            "name": name,
            "hex_file": f"stimuli/{name}.hex",
            "png_file": f"stimuli/{name}.png",
            "width": image.width,
            "height": image.height,
            "expected_ascii": ord(expected) if expected is not None else 0,
            "expected_character": expected,
            "expected_class_id": CHARACTERS.index(expected) + 1 if expected is not None else 0,
            "polarity": polarity,
            "foreground_bbox_exclusive": bbox,
            "normalized_25_hex": f"{bitmap:064X}",
            **details,
        })

    for font_name, filename in (FONTS[0], FONTS[2]):
        for size in (40, 64, 96):
            glyph = render_glyph("4", font_dir / filename, size)
            canvas = Image.new("L", (128, 128), 255)
            canvas.paste(glyph, ((128 - glyph.width) // 2, (128 - glyph.height) // 2))
            save(f"digit4_{font_name}_{size}_dark", canvas, "4", "dark_on_light", font=font_name, font_size=size)
            save(f"digit4_{font_name}_{size}_light", ImageOps.invert(canvas), "4", "light_on_dark", font=font_name, font_size=size)

    for character in "ABO0I1S5GC":
        for font_name, filename in (FONTS[0], FONTS[2]):
            glyph = render_glyph(character, font_dir / filename, 96)
            canvas = Image.new("L", (128, 128), 255)
            canvas.paste(glyph, ((128 - glyph.width) // 2, (128 - glyph.height) // 2))
            save(f"character_{character}_{font_name}_96_dark", canvas, character, "dark_on_light",
                 font=font_name, font_size=96, allow_reject=character in "O0I1")

    save("negative_empty_white", Image.new("L", (128, 128), 255), None, "dark_on_light")
    save("negative_empty_black", Image.new("L", (128, 128), 0), None, "light_on_dark")
    rectangle = Image.new("L", (128, 128), 255)
    ImageDraw.Draw(rectangle).rectangle((26, 18, 101, 109), outline=0, width=5)
    save("negative_rectangle", rectangle, None, "dark_on_light")
    face = Image.new("L", (128, 128), 255)
    draw = ImageDraw.Draw(face)
    draw.ellipse((24, 14, 103, 113), outline=0, width=4)
    draw.ellipse((42, 40, 50, 48), fill=0)
    draw.ellipse((77, 40, 85, 48), fill=0)
    draw.line((64, 50, 60, 72, 68, 72), fill=0, width=3)
    draw.arc((42, 66, 86, 95), start=10, end=170, fill=0, width=4)
    save("negative_face", face, None, "dark_on_light")
    (output_dir / "ocr_stimuli_manifest.json").write_text(
        json.dumps({"format": "8-bit grayscale, row-major, one two-digit hex pixel per line", "fixtures": records}, indent=2) + "\n",
        encoding="utf-8",
    )
    return records


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--font-dir", type=Path, default=Path("C:/Windows/Fonts"))
    args = parser.parse_args()
    for _, filename in FONTS:
        if not (args.font_dir / filename).is_file():
            parser.error(f"Required font does not exist: {args.font_dir / filename}")
    args.output_dir.mkdir(parents=True, exist_ok=True)
    templates = template_records(args.font_dir)
    write_rom(args.output_dir / "ocr_font16_rom.v", templates)
    (args.output_dir / "ocr_font16_templates.json").write_text(json.dumps(templates, indent=2) + "\n", encoding="utf-8")
    stimuli = make_stimuli(args.output_dir, args.font_dir)
    print(f"Generated {len(templates)} templates and {len(stimuli)} grayscale fixtures in {args.output_dir.resolve()}")


if __name__ == "__main__":
    main()
